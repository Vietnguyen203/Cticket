/**
 * Interface icons (docs/ui-redesign.md): one 24×24 grid, 1.75px strokes, the
 * current text colour. Decorative by default (aria-hidden); give a `title`
 * when the icon is the only label of a control.
 */
type IconProps = SVGProps<SVGSVGElement> & { size?: number; title?: string }

function Icon({ size = 20, title, children, ...rest }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      focusable="false"
      {...rest}
    >
      {title && <title>{title}</title>}
      {children}
    </svg>
  )
}

